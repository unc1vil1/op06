
SELECT s.student_id,
       s.last_name || ' ' || s.first_name ||
       COALESCE(' ' || s.middle_name, '') AS student_name,
       g.group_name
FROM students AS s
JOIN groups AS g ON g.group_id = s.group_id
ORDER BY g.group_name, s.last_name, s.first_name;

SELECT g.group_id, g.group_name, COUNT(s.student_id) AS student_count
FROM groups AS g
LEFT JOIN students AS s ON s.group_id = g.group_id
GROUP BY g.group_id, g.group_name
ORDER BY g.group_name;

SELECT l.lesson_id, l.lesson_date, l.lesson_type, g.group_name,
       d.discipline_name, d.hours,
       t.last_name || ' ' || t.first_name AS teacher_name
FROM lessons AS l
JOIN groups AS g ON g.group_id = l.group_id
JOIN disciplines AS d ON d.discipline_id = l.discipline_id
JOIN teachers AS t ON t.teacher_id = l.teacher_id
ORDER BY l.lesson_date, g.group_name;


SELECT t.teacher_id, t.last_name || ' ' || t.first_name AS teacher_name,
       COUNT(l.lesson_id) AS lesson_count
FROM teachers AS t
LEFT JOIN lessons AS l ON l.teacher_id = t.teacher_id
GROUP BY t.teacher_id, t.last_name, t.first_name
ORDER BY lesson_count DESC, teacher_name;


SELECT student_id, last_name, first_name, middle_name, birth_date
FROM students
WHERE birth_date >= DATE '2008-01-01'
ORDER BY birth_date;

SELECT discipline_id, discipline_name, hours
FROM disciplines
WHERE hours > 72
ORDER BY hours DESC;


SELECT g.group_id, g.group_name, COUNT(s.student_id) AS student_count
FROM groups AS g
JOIN students AS s ON s.group_id = g.group_id
GROUP BY g.group_id, g.group_name
HAVING COUNT(s.student_id) > 1
ORDER BY student_count DESC, g.group_name;

SELECT ROUND(AVG(lesson_count), 2) AS average_lessons_per_teacher
FROM (
    SELECT t.teacher_id, COUNT(l.lesson_id) AS lesson_count
    FROM teachers AS t
    LEFT JOIN lessons AS l ON l.teacher_id = t.teacher_id
    GROUP BY t.teacher_id
) AS teacher_load;


