SELECT s.student_id, s.last_name, s.first_name,
       ROUND(AVG(gr.grade), 2) AS average_grade,
       COUNT(gr.grade_id) AS grades_count
FROM students AS s
JOIN grades AS gr ON gr.student_id = s.student_id
GROUP BY s.student_id, s.last_name, s.first_name
ORDER BY average_grade DESC, s.last_name;


SELECT s.student_id, s.last_name, s.first_name,
       ROUND(AVG(gr.grade), 2) AS average_grade
FROM students AS s
JOIN grades AS gr ON gr.student_id = s.student_id
GROUP BY s.student_id, s.last_name, s.first_name
HAVING AVG(gr.grade) > 4.5
ORDER BY average_grade DESC, s.last_name;


CREATE TABLE IF NOT EXISTS grade_audit (
    audit_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grade_id INTEGER,
    operation VARCHAR(10) NOT NULL,
    old_grade SMALLINT,
    new_grade SMALLINT,
    changed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE OR REPLACE FUNCTION fn_grade_audit()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO grade_audit (grade_id, operation, old_grade, new_grade)
        VALUES (NEW.grade_id, 'INSERT', NULL, NEW.grade);
        RETURN NEW;
    ELSIF TG_OP = 'UPDATE' THEN
        INSERT INTO grade_audit (grade_id, operation, old_grade, new_grade)
        VALUES (NEW.grade_id, 'UPDATE', OLD.grade, NEW.grade);
        RETURN NEW;
    ELSIF TG_OP = 'DELETE' THEN
        INSERT INTO grade_audit (grade_id, operation, old_grade, new_grade)
        VALUES (OLD.grade_id, 'DELETE', OLD.grade, NULL);
        RETURN OLD;
    END IF;
    RETURN NULL;
END;
$$;

DROP TRIGGER IF EXISTS trg_grade_audit ON grades;
CREATE TRIGGER trg_grade_audit
AFTER INSERT OR UPDATE OR DELETE ON grades
FOR EACH ROW EXECUTE FUNCTION fn_grade_audit();


