BEGIN;


DROP TABLE IF EXISTS grades CASCADE;
DROP TABLE IF EXISTS lessons CASCADE;
DROP TABLE IF EXISTS students CASCADE;
DROP TABLE IF EXISTS disciplines CASCADE;
DROP TABLE IF EXISTS teachers CASCADE;
DROP TABLE IF EXISTS groups CASCADE;

CREATE TABLE groups (
    group_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_name     VARCHAR(20) NOT NULL UNIQUE,
    specialty      VARCHAR(100) NOT NULL,
    admission_year SMALLINT NOT NULL CHECK (admission_year BETWEEN 2000 AND 2100)
);

CREATE TABLE students (
    student_id  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    last_name   VARCHAR(50) NOT NULL,
    first_name  VARCHAR(50) NOT NULL,
    middle_name VARCHAR(50),
    birth_date  DATE NOT NULL,
    group_id    INTEGER NOT NULL,
    CONSTRAINT fk_students_group
        FOREIGN KEY (group_id) REFERENCES groups(group_id)
        ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE TABLE teachers (
    teacher_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    last_name  VARCHAR(50) NOT NULL,
    first_name VARCHAR(50) NOT NULL,
    department VARCHAR(100) NOT NULL
);

CREATE TABLE disciplines (
    discipline_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    discipline_name VARCHAR(100) NOT NULL UNIQUE,
    hours           INTEGER NOT NULL CHECK (hours > 0)
);

CREATE TABLE lessons (
    lesson_id     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id      INTEGER NOT NULL,
    discipline_id INTEGER NOT NULL,
    teacher_id    INTEGER NOT NULL,
    lesson_date   DATE NOT NULL,
    lesson_type   VARCHAR(30) NOT NULL,
    CONSTRAINT fk_lessons_group
        FOREIGN KEY (group_id) REFERENCES groups(group_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_lessons_discipline
        FOREIGN KEY (discipline_id) REFERENCES disciplines(discipline_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_lessons_teacher
        FOREIGN KEY (teacher_id) REFERENCES teachers(teacher_id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);


CREATE TABLE grades (
    grade_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id INTEGER NOT NULL,
    discipline_id INTEGER NOT NULL,
    grade      SMALLINT NOT NULL CHECK (grade BETWEEN 2 AND 5),
    grade_date DATE NOT NULL,
    CONSTRAINT fk_grades_student
        FOREIGN KEY (student_id) REFERENCES students(student_id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_grades_discipline
        FOREIGN KEY (discipline_id) REFERENCES disciplines(discipline_id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);


